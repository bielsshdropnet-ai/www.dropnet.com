        let idiomaAtual = 'pt';

        function aplicarIdioma(lang) {
            const dic = traducoes[lang];
            if (!dic) return;
            idiomaAtual = lang;

            document.title = dic.tituloPagina;
            document.getElementById('htmlRoot').setAttribute('lang', dic.htmlLang);
            document.getElementById('metaDescricao').setAttribute('content', dic['inicio.subtitulo']);
            document.getElementById('ogTitulo').setAttribute('content', dic.tituloPagina);
            document.getElementById('ogDescricao').setAttribute('content', dic['inicio.subtitulo']);

            document.querySelectorAll('[data-i18n]').forEach(el => {
                const chave = el.getAttribute('data-i18n');
                if (dic[chave] !== undefined) {
                    el.innerHTML = dic[chave];
                }
            });

            document.querySelectorAll('.btn-idioma').forEach(btn => {
                const ativo = btn.dataset.lang === lang;
                btn.classList.toggle('ativo', ativo);
                btn.setAttribute('aria-pressed', ativo ? 'true' : 'false');
            });

            atualizarAnoRodape();
            verificarHorario();
            localStorage.setItem('idioma', lang);
        }

