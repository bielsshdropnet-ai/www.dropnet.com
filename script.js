        function verificarHorario() {
            const agora = new Date();
            const diaSemana = agora.getDay();
            const hora = agora.getHours();
            const minuto = agora.getMinutes();
            const totalMinutos = hora * 60 + minuto;

            const caixa = document.getElementById('caixa-horario');
            const texto = document.getElementById('texto-status');
            let aberto = false;

            if (diaSemana >= 1 && diaSemana <= 5) {
                aberto = totalMinutos >= 480 && totalMinutos <= 1440;
            } else if (diaSemana === 6) {
                aberto = totalMinutos >= 480 && totalMinutos <= 1320;
            } else {
                aberto = false;
            }

            const dic = traducoes[idiomaAtual];

            if (aberto) {
                caixa.className = 'status-atendimento aberto';
                texto.className = 'status-titulo aberto';
                texto.innerHTML = '<i class="fas fa-circle"></i> ' + dic['status.aberto'];
            } else {
                caixa.className = 'status-atendimento fechado';
                texto.className = 'status-titulo fechado';
                texto.innerHTML = '<i class="fas fa-circle"></i> ' + dic['status.fechado'];
            }
        }

